//! Parity of `SplineTransformer` with sklearn 1.8.0
//! `sklearn.preprocessing.SplineTransformer`.
//!
//! Reference script: rng = RandomState(1); X = round(uniform(0, 10, (12, 2)), 3);
//! X[:, 1] = round(X[:, 1] ** 1.5 / 5, 3); test points include values
//! outside the training range.

use anofox_ml_core::{FitUnsupervised, Transform};
use anofox_ml_preprocessing::{Extrapolation, SplineKnots, SplineTransformer};
use ndarray::Array2;

const X: [f64; 24] = [
    4.17, 3.866, 0.001, 1.051, 1.468, 0.177, 1.863, 1.285, 3.968, 2.501, 4.192, 3.587, 2.045,
    5.204, 0.274, 3.472, 4.173, 2.641, 1.404, 0.558, 8.007, 6.026, 3.134, 3.643,
];
const XT: [f64; 8] = [-1.0, 0.2, 2.5, 1.0, 5.0, 3.3, 11.0, 8.0];

fn check(t: SplineTransformer, cols: usize, expected: &[f64], ctx: &str) {
    let x = Array2::from_shape_vec((12, 2), X.to_vec()).unwrap();
    let xt = Array2::from_shape_vec((4, 2), XT.to_vec()).unwrap();
    let fitted = FitUnsupervised::<f64>::fit(&t, &x).unwrap();
    assert_eq!(fitted.n_output_features(), cols, "{ctx}");
    let out = fitted.transform(&xt).unwrap();
    assert_eq!(out.dim(), (4, cols), "{ctx}");
    for (i, (g, w)) in out.iter().zip(expected).enumerate() {
        assert!((g - w).abs() < 1e-12, "{ctx}[{i}]: {g} vs sklearn {w}");
    }
}

