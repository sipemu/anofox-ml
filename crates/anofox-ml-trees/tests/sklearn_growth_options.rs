fn close(a: &Array1<f64>, b: &[f64]) {
    for (u, v) in a.iter().zip(b) {
        assert!((u - v).abs() < 1e-9, "{a} vs {b:?}");
    }
}

#[test]
fn regressor_options_match_sklearn() {
    let (x, y) = data();
    let w = Array1::from_shape_fn(60, |i| 1.0 + (i % 3) as f64);
    let q = x.slice(s![..6, ..]).to_owned();
    let fit = |t: DecisionTreeRegressor| {
        t.fit_weighted(&x, &y, Some(&w))
            .unwrap()
            .predict(&q)
            .unwrap()
    };
    let mid = [
        1.7069126002462203,
        0.699407568091606,
        1.7069126002462203,
        1.7069126002462203,
        2.80678912048192,
        1.7069126002462203,
    ];
    close(
        &fit(DecisionTreeRegressor::new().with_max_leaf_nodes(Some(5))),
        &mid,
    );
    close(
        &fit(DecisionTreeRegressor::new().with_min_impurity_decrease(0.05)),
        &mid,
    );
    close(
        &fit(DecisionTreeRegressor::new().with_ccp_alpha(0.02)),
        &[
            2.1263215512790774,
            0.6994075680916061,
            2.1844948333057497,
            1.3421823110675133,
            3.161842336379998,
            1.3421823110675133,
        ],
    );
    close(
        &fit(DecisionTreeRegressor::new().with_min_weight_fraction_leaf(0.1)),
        &[
            1.7665403360321887,
            -0.03306187985731116,
            2.1844948333057506,
            1.1907806761941087,
            3.1618423363799977,
            1.1907806761941087,
        ],
    );
}

#[test]
fn classifier_options_match_sklearn() {
    let (x, y) = data();
    let yc = y.mapv(|v| f64::from(v > 1.5) + f64::from(v > 2.5));
    let q = x.slice(s![..6, ..]).to_owned();
    let f = Fit::fit(
        &DecisionTreeClassifier::new().with_max_leaf_nodes(Some(4)),
        &x,
        &yc,
    )
    .unwrap();
    assert_eq!(
        f.predict(&q).unwrap().to_vec(),
        vec![1.0, 0.0, 1.0, 1.0, 2.0, 1.0]
    );
    assert_eq!(f.tree().n_leaves(), 4);
    let f = Fit::fit(&DecisionTreeClassifier::new().with_ccp_alpha(0.01), &x, &yc).unwrap();
    assert_eq!(
        f.predict(&q).unwrap().to_vec(),
        vec![0.0, 0.0, 1.0, 0.0, 2.0, 1.0]
    );
    assert_eq!(f.tree().n_leaves(), 13);
}
