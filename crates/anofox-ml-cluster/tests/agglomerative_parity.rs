#[test]
fn distance_threshold_matches_sklearn() {
    // AgglomerativeClustering(n_clusters=None, distance_threshold=1.5, linkage="average")
    let f = AgglomerativeClustering::new(1)
        .with_linkage(Linkage::Average)
        .with_distance_threshold(Some(1.5))
        .fit(&data())
        .unwrap();
    assert_eq!(f.n_clusters, 3);
    let l: Vec<usize> = f.labels.iter().map(|&v| v as usize).collect();
    assert_eq!(
        l,
        [
            0, 2, 1, 0, 2, 1, 0, 2, 1, 0, 2, 1, 0, 2, 1, 0, 2, 1, 0, 2, 1, 0, 2, 1, 0, 2, 1, 0, 2,
            1
        ]
    );
}
