//! sklearn 1.8 parity of AgglomerativeClustering (#61): scipy's linkage
//! (MST single linkage, nn-chain for the others), its relabelling, and
//! sklearn's `_hc_cut` label order, with `n_clusters` or
//! `distance_threshold`.

use anofox_ml_cluster::{AgglomerativeClustering, Linkage};
use anofox_ml_core::FitUnsupervised;
use ndarray::Array2;

fn data() -> Array2<f64> {
    Array2::from_shape_fn((30, 2), |(i, j)| {
        let (fi, fj) = (i as f64, j as f64);
        (fi * 0.6180339887 * (fj + 1.0) + fi * fi * 0.0137 * (fj + 3.0)) % 1.0
            + 2.0 * (i % 3) as f64
    })
}

