//! sklearn 1.8 parity of Birch (#61): CF-tree insertion, merged-radius
//! threshold, node and root splits, leaf order of the subcluster centres,
//! and the AgglomerativeClustering global step.

use anofox_ml_cluster::Birch;
use anofox_ml_core::FitUnsupervised;
use ndarray::Array2;

fn data() -> Array2<f64> {
    let centres = [(0.0, 0.0), (4.0, 0.0), (2.0, 4.0), (8.0, 8.0)];
    let spread = [0.5, 0.7, 0.4, 1.0];
    Array2::from_shape_fn((200, 2), |(i, j)| {
        let fi = i as f64;
        let (c, s) = (centres[i % 4], spread[i % 4]);
        if j == 0 {
            c.0 + ((fi * 0.6180339887) % 1.0 - 0.5) * 2.0 * s
        } else {
            c.1 + ((fi * 0.4142135623 + fi * fi * 0.001) % 1.0 - 0.5) * 2.0 * s
        }
    })
}

fn check(b: Birch, centers: &[f64], sub_labels: &[usize], labels: &[usize]) {
    let f = b.fit(&data()).unwrap();
    assert_eq!(f.subcluster_centers.len(), centers.len());
    for (a, e) in f.subcluster_centers.iter().zip(centers) {
        assert!((a - e).abs() < 1e-12, "{a} vs {e}");
    }
    let sl: Vec<usize> = f.subcluster_labels.iter().map(|&v| v as usize).collect();
    assert_eq!(sl, sub_labels);
    let l: Vec<usize> = f.labels.iter().map(|&v| v as usize).collect();
    assert_eq!(l, labels);
}

